save_candidate_heatmap <- function(
    selected_miRNAs,
    contrast_name,
    metadata_subset,
    group_variable,
    group_levels,
    group_labels,
    candidate_type = c(
      "raw",
      "fdr"
    )
) {

  candidate_type <- match.arg(
    candidate_type
  )

  selected_miRNAs <- intersect(
    unique(
      selected_miRNAs
    ),
    rownames(
      heatmap_z
    )
  )

  candidate_label <- if (
    candidate_type == "raw"
  ) {
    "raw p < 0.05"
  } else {
    "BH-FDR < 0.05"
  }

  output_dir <- if (
    candidate_type == "raw"
  ) {
    heatmap_raw_dir
  } else {
