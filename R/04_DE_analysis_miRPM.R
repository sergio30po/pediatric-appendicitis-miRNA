run_pairwise_phenotype <- function(
    lower_group,
    higher_group,
    contrast_name
) {

  lower_label <- phenotype_label(
    lower_group
  )

  higher_label <- phenotype_label(
    higher_group
  )

  message(
    "Running miRPM pairwise comparison: ",
    lower_label,
    " versus ",
    higher_label
  )

  keep <- metadata$Phenotype %in% c(
    lower_group,
    higher_group
  )

  metadata_pair <- droplevels(
    metadata[
      keep,
      ,
      drop = FALSE
    ]
  )

  rpm_pair <- rpm[
    ,
    metadata_pair$Sample,
    drop = FALSE
  ]

  # Group order is intentionally higher, lower so positive effects correspond
  # to increased expression in the second/more severe phenotype.

  analysis_result <- run_mirpm_two_group(
    rpm_matrix = rpm_pair,
    metadata_subset = metadata_pair,
    condition = "Phenotype",
    group_order = c(
      higher_group,
      lower_group
    ),
    contrast_name = contrast_name,
    positive_effect_label = paste0(
      "Positive effect = higher in ",
      higher_label,
      " than ",
      lower_label
    )
  )

  plot_fdr_effect_summary(
    analysis_result,
    contrast_name = contrast_name,
    title = paste0(
      "RPM differential expression: ",
      higher_label,
      " versus ",
      lower_label
    ),
    x_label = paste0(
      "Log2 median ratio (",
      higher_label,
      " / ",
      lower_label,
      ")"
    )
  )

  plot_fdr_expression(
    analysis_result,
    contrast_name = contrast_name,
    metadata_subset = metadata_pair,
    group_variable = "Phenotype",
    plot_group_order = c(
      lower_group,
      higher_group
    ),
    plot_group_labels = c(
      lower_label,
      higher_label
    )
  )

  save_candidate_heatmap(
    selected_miRNAs = analysis_result$raw_candidates$miRNA,
    contrast_name = contrast_name,
    metadata_subset = metadata_pair,
    group_variable = "Phenotype",
    group_levels = c(
      lower_group,
      higher_group
    ),
    group_labels = c(
      lower_label,
      higher_label
    ),
    candidate_type = "raw"
  )

  save_candidate_heatmap(
    selected_miRNAs = analysis_result$fdr_candidates$miRNA,
    contrast_name = contrast_name,
    metadata_subset = metadata_pair,
    group_variable = "Phenotype",
    group_levels = c(
      lower_group,
      higher_group
    ),
    group_labels = c(
      lower_label,
      higher_label
    ),
    candidate_type = "fdr"
  )

  save_candidate_pca(
    selected_miRNAs = analysis_result$raw_candidates$miRNA,
    contrast_name = contrast_name,
    metadata_subset = metadata_pair,
    group_variable = "Phenotype",
    group_levels = c(
      lower_group,
      higher_group
    ),
    group_labels = c(
      lower_label,
      higher_label
    ),
    candidate_type = "raw"
  )

