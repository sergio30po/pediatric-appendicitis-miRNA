# ==============================================================================
# 04_DE_analysis_miRPM.R
# ==============================================================================
#
# Project:
#   Pediatric appendicitis plasma miRNA-seq
#
# Script:
#   04_DE_analysis_miRPM.R
#
# Purpose:
#   Perform RPM-based non-parametric differential-expression analysis using the
#   package-native miRPM workflow across the complete prespecified filtered
#   feature set and retain all nominal, recurrent and FDR-supported signals for
#   subsequent cross-method validation.
#
# Role in pipeline:
#   Primary RPM-based non-parametric differential-expression layer.
#
# IMPORTANT:
#   This script does NOT select or force a predefined manuscript miRNA panel.
#
#   All miRNAs retained by the prespecified expression filter are tested
#   without reference to historical candidate lists.
#
#   Candidate outputs are descriptive/exploratory summaries of the signals that
#   arise naturally from the current analysis.
#
# Clinical labels inherited from script 01:
#
#   Phenotype:
#       NIA / Mild / Severe
#
#   Phenotype_full:
#       Non-inflamed appendix
#       Mild appendicitis
#       Severe appendicitis
#
#   Appendicitis_status:
#       NIA / Appendicitis
#
#   NIA = non-inflamed appendix.
#   NIA is not a healthy-control cohort.
#
# Feature set:
#   Complete filtered miRNA set generated by script 01.
#   The feature set is inherited from the prespecified filtering step.
#
# Statistical analyses:
#
#   1. Appendicitis versus NIA
#      Mann-Whitney-Wilcoxon through miRPM.
#
#   2. Global NIA / Mild / Severe
#      Kruskal-Wallis through miRPM.
#
#   3. Prespecified pairwise clinical-group comparisons
#      NIA versus Mild
#      NIA versus Severe
#      Mild versus Severe
#
#      Each pairwise comparison is run as an independent two-group miRPM
#      analysis to preserve the intended Mann-Whitney-Wilcoxon framework.
#
# Multiple testing:
#   Primary correction:
#       Benjamini-Hochberg FDR across all tested miRNAs within each analysis.
#
#   Additional audit:
#       Holm correction.
#
#   Raw p < 0.05:
#       exploratory only.
#
# Exploratory signal tiers:
#
#   FDR_supported:
#       FDR < 0.05 in at least one prespecified analysis.
#
#   recurrent_nominal:
#       raw p < 0.05 in at least two prespecified analyses but no FDR < 0.05.
#
#   single_nominal:
#       raw p < 0.05 in exactly one prespecified analysis but no FDR < 0.05.
#
#   no_nominal_signal:
#       no raw p < 0.05 in any prespecified analysis.
#
# IMPORTANT:
#   These tiers are NOT additional hypothesis tests and do not alter p-values.
#   The five analyses are not statistically independent, so recurrence counts
#   are descriptive only. Their purpose is to preserve potentially relevant
#   signals for subsequent edgeR/DESeq2 and integrated-method validation.
#
# Visualization:
#   Candidate heatmaps:
#       row Z-scores of log2(RPM + 1).
#
#   Candidate PCA:
#       explicitly exploratory/post-selection.
#
#   Raw-p and FDR candidate plots are contrast-specific visualization aids and
#   must not be interpreted as independent validation.
#
# No sample or miRNA is removed in this script beyond the frozen feature set
# inherited from script 01.
#
# Inputs:
#   results/<analysis_id>/filtered_RPM.rds
#   results/<analysis_id>/metadata_analysis_samples.rds
#
# Main outputs:
#   results/<analysis_id>/de_rpm/
#
#     DE_RPM_analysis_manifest.csv
#     DE_RPM_analysis_summary.csv
#     DE_RPM_results.xlsx
#
#     DE_RPM_all_contrasts_long.csv
#     DE_RPM_candidate_signal_summary.csv
#     DE_RPM_candidate_any_nominal.csv
#     DE_RPM_candidate_recurrent_nominal.csv
#     DE_RPM_candidate_FDR_supported.csv
#
#     Candidate-set exploratory visualizations:
#       figures/<analysis_id>/de_rpm/hm/summary/
#       figures/<analysis_id>/de_rpm/pca/summary/
#
#       - any nominal signal set (p < 0.05 in >=1 analysis)
#       - recurrent nominal signal set (p < 0.05 in >=2 analyses)
#
#     tab/
#       complete result tables for every analysis
#
#     cand/raw/
#       nominal raw-p candidate sets
#
#     cand/fdr/
#       BH-FDR candidate sets
#
#     cand/holm/
#       Holm candidate sets
#
#     04_final_QC_summary.csv
#
# Reproducibility:
#   Clinical labels and cohort membership are inherited from script 01.
#   This script never recreates 0/1/2 clinical labels independently.
#   No historical candidate list is used as an analysis input.
#
# ==============================================================================


