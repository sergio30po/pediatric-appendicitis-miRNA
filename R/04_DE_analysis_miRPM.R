contrast_code <- function(
    contrast_name
) {
  codes <- c(
    Appendicitis_vs_NIA = "AvN",
    Phenotype_global = "Pg",
    NIA_vs_Mild = "NvM",
    NIA_vs_Severe = "NvS",
    Mild_vs_Severe = "MvS"
  )

  code <- unname(
    codes[
      contrast_name
    ]
  )

  if (
    length(
      code
    ) != 1L ||
    is.na(
      code
    )
  ) {
    stop(
      "Unknown contrast name: ",
      contrast_name,
      call. = FALSE
    )
  }

  code
}

