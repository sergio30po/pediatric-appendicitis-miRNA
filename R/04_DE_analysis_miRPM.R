collapse_contrasts <- function(
    x,
    flag
) {

  hits <- x[
    !is.na(
      flag
    ) &
      flag
  ]

  if (
    length(
      hits
    ) == 0L
  ) {

    return(
      ""
    )
  }

  paste(
    unique(
      hits
    ),
    collapse = "; "
  )
}


safe_min <- function(
    x
) {

  x <- x[
    is.finite(
      x
    )
  ]

  if (
    length(
      x
    ) == 0L
  ) {

    return(
      NA_real_
    )
  }

  min(
    x
  )
}


best_contrast_from_metric <- function(
    contrast,
    metric
) {

  usable <- (
    !is.na(
      metric
    ) &
      is.finite(
        metric
      )
  )

  if (!any(
    usable
  )) {

    return(
      ""
    )
  }

  contrast[
    which.min(
      ifelse(
        usable,
        metric,
        Inf
      )
    )
  ][1L]
}


