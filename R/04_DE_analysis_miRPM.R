# ==============================================================================
# 5.8 Exploratory PCA and heatmaps of cross-analysis candidate sets
# ==============================================================================

# IMPORTANT:
#   These plots are post-selection visualizations.
#
#   The same clinical labels used to identify differential-expression signals
#   are also used to display the samples. Therefore, apparent separation in
#   these PCA/heatmap figures is descriptive and must not be interpreted as
#   independent evidence of diagnostic or prognostic performance.
#
# Two data-driven candidate sets are visualized:
#
#   any_nominal:
#       raw p < 0.05 in at least one of the five prespecified analyses.
#
#   recurrent_nominal:
#       raw p < 0.05 in at least two of the five prespecified analyses.
#
# No historical miRNA list is used.


save_cross_analysis_heatmap <- function(
    selected_miRNAs,
    set_code,
    set_label
) {

  selected_miRNAs <- intersect(
    unique(
      selected_miRNAs
    ),
    rownames(
      heatmap_z
    )
  )


  if (
    length(
      selected_miRNAs
    ) == 0L
  ) {

    message(
      "Cross-analysis heatmap skipped for ",
      set_label,
      ": no miRNAs."
    )

    return(
      invisible(
        NULL
      )
    )
  }


  plot_metadata <- metadata |>
    dplyr::arrange(
      Phenotype,
      Sample
    )


  ordered_samples <- plot_metadata$Sample


  heatmap_matrix <- heatmap_z[
    selected_miRNAs,
    ordered_samples,
    drop = FALSE
  ]


  annotation <- ComplexHeatmap::HeatmapAnnotation(
    Phenotype = plot_metadata$Phenotype,
    annotation_name_side = "left"
  )


  heatmap_object <- ComplexHeatmap::Heatmap(

    heatmap_matrix,

    name = "Row Z-score",

    col = circlize::colorRamp2(
      c(
        -2,
        0,
        2
      ),
      c(
        "navy",
        "white",
        "firebrick3"
      )
    ),

    top_annotation = annotation,

    column_split = plot_metadata$Phenotype,

    cluster_rows = length(
      selected_miRNAs
    ) > 1L,

    cluster_columns = FALSE,

    show_column_names = FALSE,

    show_row_names = TRUE,

    row_names_gp = grid::gpar(
      fontsize = if (
        length(
          selected_miRNAs
        ) > 35L
      ) {
        6.5
      } else {
        8
      }
    ),

    column_title = paste0(
      set_label,
      " (",
      length(
        selected_miRNAs
      ),
      " miRNAs)"
    ),

    use_raster = FALSE
  )


  draw_heatmap <- function() {

    ComplexHeatmap::draw(
      heatmap_object,
      heatmap_legend_side = "right",
      annotation_legend_side = "right"
    )
  }


  figure_height <- max(
    6,
    min(
      12,
      0.18 *
        length(
          selected_miRNAs
        ) +
        3.5
    )
  )


  draw_to_pdf(
    filename = file.path(
      candidate_summary_heatmap_dir,
      paste0(
        set_code,
        "_heatmap.pdf"
      )
    ),
    width = 8,
    height = figure_height,
    draw = draw_heatmap
  )


  draw_to_tiff(
    filename = file.path(
      candidate_summary_heatmap_dir,
      paste0(
        set_code,
        "_heatmap.tiff"
      )
    ),
    width = 8,
    height = figure_height,
    units = "in",
    res = 600,
    compression = "lzw",
    draw = draw_heatmap
  )


  utils::write.csv(
    data.frame(
      candidate_set = set_code,
      candidate_definition = set_label,
      miRNA = selected_miRNAs,
      stringsAsFactors = FALSE
    ),
    prepare_output_file(
      file.path(
        candidate_summary_heatmap_dir,
        paste0(
          set_code,
          "_miRNAs.csv"
        )
      )
    ),
    row.names = FALSE
  )


  invisible(
    heatmap_object
  )
}


save_cross_analysis_pca <- function(
    selected_miRNAs,
    set_code,
    set_label
) {

  selected_miRNAs <- intersect(
    unique(
      selected_miRNAs
    ),
    rownames(
      rpm
    )
  )


  if (
    length(
      selected_miRNAs
    ) < 2L
  ) {

    message(
      "Cross-analysis PCA skipped for ",
      set_label,
      ": fewer than two miRNAs."
    )

    return(
      invisible(
        NULL
      )
    )
  }


  pca_matrix <- log2(
    rpm[
      selected_miRNAs,
      metadata$Sample,
      drop = FALSE
    ] +
      1
  )


  feature_sd <- apply(
    pca_matrix,
    1L,
    stats::sd
  )


  usable_features <- (
    is.finite(
      feature_sd
    ) &
      feature_sd > 0
  )


  pca_matrix <- pca_matrix[
    usable_features,
    ,
    drop = FALSE
  ]


  if (
    nrow(
      pca_matrix
    ) < 2L
  ) {

    message(
      "Cross-analysis PCA skipped for ",
      set_label,
      ": fewer than two variable miRNAs."
    )

    return(
      invisible(
        NULL
      )
    )
  }


  pca_object <- stats::prcomp(
    t(
      pca_matrix
    ),
    center = TRUE,
    scale. = TRUE
  )


  variance <- (
    pca_object$sdev^2
  ) /
    sum(
      pca_object$sdev^2
    )


  pca_coordinates <- data.frame(
    Sample = rownames(
      pca_object$x
    ),
    PC1 = pca_object$x[
      ,
      1L
    ],
    PC2 = pca_object$x[
      ,
      2L
    ],
    stringsAsFactors = FALSE
  )


  if (
    ncol(
      pca_object$x
    ) >= 3L
  ) {

    pca_coordinates$PC3 <- pca_object$x[
      ,
      3L
    ]
  }


  pca_coordinates <- dplyr::left_join(
    pca_coordinates,
    metadata[
      ,
      c(
        "Sample",
        "Phenotype",
        "Phenotype_full",
        "Appendicitis_status",
        "Sex",
        "Age"
      ),
      drop = FALSE
    ],
    by = "Sample"
  )


  pca_variance <- data.frame(
    PC = paste0(
      "PC",
      seq_along(
        variance
      )
    ),
    variance_explained = variance,
    variance_explained_pct = 100 *
      variance,
    cumulative_variance_explained_pct = 100 *
      cumsum(
        variance
      ),
    stringsAsFactors = FALSE
  )


  utils::write.csv(
    pca_coordinates,
    prepare_output_file(
      file.path(
        candidate_summary_pca_dir,
        paste0(
          set_code,
          "_PCA_coordinates.csv"
        )
      )
    ),
    row.names = FALSE
  )


  utils::write.csv(
    pca_variance,
    prepare_output_file(
      file.path(
        candidate_summary_pca_dir,
        paste0(
          set_code,
          "_PCA_variance.csv"
        )
      )
    ),
    row.names = FALSE
  )


  utils::write.csv(
    data.frame(
      candidate_set = set_code,
      candidate_definition = set_label,
      miRNA = rownames(
        pca_matrix
      ),
      stringsAsFactors = FALSE
    ),
    prepare_output_file(
      file.path(
        candidate_summary_pca_dir,
        paste0(
          set_code,
          "_miRNAs.csv"
        )
      )
    ),
    row.names = FALSE
  )


  group_counts <- table(
    pca_coordinates$Phenotype
  )


  eligible_groups <- names(
    group_counts[
      group_counts >= 3L
    ]
  )


  ellipse_data <- pca_coordinates[
    as.character(
      pca_coordinates$Phenotype
    ) %in%
      eligible_groups,
    ,
    drop = FALSE
  ]


  plot_object <- ggplot2::ggplot(
    pca_coordinates,
    ggplot2::aes(
      x = PC1,
      y = PC2,
      color = Phenotype
    )
  )


  if (
    nrow(
      ellipse_data
    ) > 0L
  ) {

    plot_object <- plot_object +
      ggplot2::stat_ellipse(
        data = ellipse_data,
        ggplot2::aes(
          fill = Phenotype
        ),
        geom = "polygon",
        type = "norm",
        level = 0.95,
        alpha = 0.12,
        color = NA,
        show.legend = FALSE
      ) +
      ggplot2::stat_ellipse(
        data = ellipse_data,
        type = "norm",
        level = 0.95,
        linewidth = 0.6,
        alpha = 0.85,
        show.legend = FALSE
      )
  }


  plot_object <- plot_object +
    ggplot2::geom_point(
      size = 3,
      alpha = 0.95
    ) +
    ggplot2::labs(
      title = paste0(
        set_label,
        " — exploratory PCA"
      ),
      subtitle = paste0(
        nrow(
          pca_matrix
        ),
        " miRNAs; post-selection visualization"
      ),
      x = sprintf(
        "PC1 (%.1f%%)",
        100 *
          variance[1L]
      ),
      y = sprintf(
        "PC2 (%.1f%%)",
        100 *
          variance[2L]
      ),
      color = NULL
    ) +
    ggplot2::theme_classic(
      base_size = 11
    ) +
    ggplot2::theme(
      plot.title = ggplot2::element_text(
        face = "bold"
      ),
      legend.position = "right"
    )


  save_ggplot_pdf(
    plot = plot_object,
    filename = file.path(
      candidate_summary_pca_dir,
      paste0(
        set_code,
        "_PCA_PC1_PC2.pdf"
      )
    ),
    width = 7,
    height = 5
  )


  save_ggplot_tiff(
    plot = plot_object,
    filename = file.path(
      candidate_summary_pca_dir,
      paste0(
        set_code,
        "_PCA_PC1_PC2.tiff"
      )
    ),
    width = 7,
    height = 5,
    dpi = 600
  )


  invisible(
    list(
      pca = pca_object,
      coordinates = pca_coordinates,
      variance = pca_variance,
      miRNAs = rownames(
        pca_matrix
      ),
      plot = plot_object
    )
  )
}


