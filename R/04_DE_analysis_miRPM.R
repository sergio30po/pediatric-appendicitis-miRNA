phenotype_label <- function(
    group_name
) {

  valid_groups <- c(
    "NIA",
    "Mild",
    "Severe"
  )

  group_name <- as.character(
    group_name
  )

  if (
    length(group_name) != 1L ||
    !group_name %in% valid_groups
  ) {
    stop(
      "Unknown phenotype group: ",
      paste(
        group_name,
        collapse = ", "
      ),
      call. = FALSE
    )
  }

  group_name
}


