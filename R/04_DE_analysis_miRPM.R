    filename = tiff_file,
    width = 7,
    height = figure_height,
    units = "in",
    res = 600,
    compression = "lzw",
    draw = draw_heatmap
  )

  invisible(
    heatmap_object
  )
}



# ------------------------------------------------------------------------------
# Candidate PCA helper
# ------------------------------------------------------------------------------

# Candidate PCA is deliberately post-selection and therefore exploratory.
# Two versions are generated:
#   - raw p < 0.05 candidates
#   - BH-FDR < 0.05 candidates
#
# These PCA plots must not be interpreted as independent evidence that groups
# separate, because the features were selected using the same outcome labels.

save_candidate_pca <- function(
    selected_miRNAs,
    contrast_name,
    metadata_subset,
    group_variable,
    group_levels,
    group_labels,
    candidate_type = c(
      "raw",
      "fdr"
    ),
    ellipse_level = 0.95
) {

  candidate_type <- match.arg(
    candidate_type
  )

  selected_miRNAs <- intersect(
    unique(
      selected_miRNAs
    ),
    rownames(
      rpm
    )
  )

  candidate_label <- if (
    candidate_type == "raw"
  ) {
    "raw p < 0.05"
  } else {
    "BH-FDR < 0.05"
  }

  output_dir <- if (
    candidate_type == "raw"
  ) {
    candidate_pca_raw_dir
  } else {
    candidate_pca_fdr_dir
  }

  if (length(selected_miRNAs) < 2L) {
    message(
      "Candidate PCA skipped for ",
      contrast_name,
      " [",
      candidate_label,
      "]: fewer than 2 candidate miRNAs."
    )

    return(
      invisible(
        NULL
      )
    )
  }

  pca_metadata <- metadata_subset[
    metadata_subset$Sample %in%
      colnames(
        rpm
      ),
    ,
    drop = FALSE
  ]

  pca_metadata <- pca_metadata[
    match(
      colnames(
        rpm[
          ,
          pca_metadata$Sample,
          drop = FALSE
        ]
      ),
      pca_metadata$Sample
    ),
    ,
    drop = FALSE
  ]

  pca_samples <- pca_metadata$Sample

  candidate_log2_rpm <- log2(
    rpm[
      selected_miRNAs,
      pca_samples,
      drop = FALSE
    ] + 1
  )

  feature_sd <- apply(
    candidate_log2_rpm,
    1,
    stats::sd
  )

  usable_features <- (
    is.finite(
      feature_sd
    ) &
      feature_sd > 0
  )

  candidate_log2_rpm <- candidate_log2_rpm[
    usable_features,
    ,
    drop = FALSE
  ]

  if (nrow(candidate_log2_rpm) < 2L) {
    message(
      "Candidate PCA skipped for ",
      contrast_name,
      " [",
      candidate_label,
      "]: fewer than 2 non-zero-variance candidate miRNAs."
    )

    return(
      invisible(
        NULL
      )
    )
  }

  pca_input <- t(
    candidate_log2_rpm
  )

  pca <- stats::prcomp(
    pca_input,
    center = TRUE,
    scale. = TRUE
  )

  if (ncol(pca$x) < 2L) {
    message(
      "Candidate PCA skipped for ",
      contrast_name,
      " [",
      candidate_label,
      "]: PCA returned fewer than 2 components."
    )

    return(
      invisible(
        NULL
      )
    )
  }

  variance <- (
    pca$sdev^2
  ) / sum(
    pca$sdev^2
  )

  pca_df <- data.frame(
    Sample = rownames(
      pca$x
    ),
    PC1 = pca$x[, 1],
    PC2 = pca$x[, 2],
    stringsAsFactors = FALSE
  )

  if (ncol(pca$x) >= 3L) {
    pca_df$PC3 <- pca$x[, 3]
  }

  pca_df <- dplyr::left_join(
    pca_df,
    pca_metadata,
    by = "Sample"
  )

  pca_df$Plot_group <- factor(
    as.character(
      pca_df[[group_variable]]
    ),
    levels = group_levels,
    labels = group_labels
  )

  utils::write.csv(
    pca_df,
    file.path(
      output_dir,
      paste0(
        contrast_code(contrast_name),
        "_coords.csv"
      )
    ),
    row.names = FALSE
  )

  candidate_variance <- data.frame(
    PC = paste0(
      "PC",
      seq_along(
        variance
      )
    ),
    variance_explained = variance,
    variance_explained_pct = 100 * variance,
    cumulative_variance_explained_pct = 100 * cumsum(
      variance
    ),
    stringsAsFactors = FALSE
  )

  utils::write.csv(
    candidate_variance,
    file.path(
      output_dir,
      paste0(
        contrast_code(contrast_name),
        "_var.csv"
      )
    ),
    row.names = FALSE
  )

  candidate_manifest <- data.frame(
    contrast = contrast_name,
    candidate_definition = candidate_label,
    miRNA = rownames(
      candidate_log2_rpm
    ),
    stringsAsFactors = FALSE
  )

  utils::write.csv(
    candidate_manifest,
    file.path(
      output_dir,
      paste0(
        contrast_code(contrast_name),
        "_mirnas.csv"
      )
    ),
    row.names = FALSE
  )

  group_counts <- table(
    pca_df$Plot_group
  )

  eligible_groups <- names(
    group_counts[
      group_counts >= 3
    ]
  )

  ellipse_data <- pca_df[
    as.character(
      pca_df$Plot_group
    ) %in%
      eligible_groups,
    ,
    drop = FALSE
  ]

  p <- ggplot2::ggplot(
    pca_df,
    ggplot2::aes(
      x = PC1,
      y = PC2,
      color = Plot_group
    )
  )

  if (nrow(ellipse_data) > 0) {
    p <- p +
      ggplot2::stat_ellipse(
        data = ellipse_data,
        ggplot2::aes(
          fill = Plot_group
        ),
        geom = "polygon",
        type = "norm",
        level = ellipse_level,
        alpha = 0.12,
        color = NA,
        show.legend = FALSE
      ) +
      ggplot2::stat_ellipse(
        data = ellipse_data,
        type = "norm",
        level = ellipse_level,
        linewidth = 0.6,
        alpha = 0.85,
        show.legend = FALSE
      )
  }

  p <- p +
    ggplot2::geom_point(
      size = 3,
      alpha = 0.95
    ) +
    ggplot2::labs(
      title = paste0(
        "Candidate PCA — ",
        contrast_name
      ),
      subtitle = paste0(
        nrow(
          candidate_log2_rpm
        ),
        " miRNAs selected at ",
        candidate_label,
        "; exploratory post-selection visualization"
      ),
      x = sprintf(
        "PC1 (%.1f%%)",
        100 * variance[1]
      ),
      y = sprintf(
        "PC2 (%.1f%%)",
        100 * variance[2]
      ),
      color = NULL
    ) +
    ggplot2::theme_classic(
      base_size = 10
    ) +
    ggplot2::theme(
      plot.title = ggplot2::element_text(
        face = "bold"
      ),
      legend.position = "right"
    )

  pca_prefix <- contrast_code(
    contrast_name
  )

  save_ggplot_pdf(
    plot = p,
    filename = file.path(
      output_dir,
      paste0(
        pca_prefix,
        "_pc12.pdf"
      )
    ),
    width = 7,
    height = 5
  )

  save_ggplot_tiff(
    plot = p,
    filename = file.path(
      output_dir,
      paste0(
        pca_prefix,
        "_pc12.tiff"
      )
    ),
    width = 7,
    height = 5,
    dpi = 600
  )

  if (ncol(pca$x) >= 3L) {

    p13 <- ggplot2::ggplot(
      pca_df,
      ggplot2::aes(
        x = PC1,
        y = PC3,
        color = Plot_group
      )
    )

    if (nrow(ellipse_data) > 0) {
      p13 <- p13 +
        ggplot2::stat_ellipse(
          data = ellipse_data,
          ggplot2::aes(
            fill = Plot_group
          ),
          geom = "polygon",
          type = "norm",
          level = ellipse_level,
          alpha = 0.12,
          color = NA,
          show.legend = FALSE
        ) +
        ggplot2::stat_ellipse(
          data = ellipse_data,
          type = "norm",
          level = ellipse_level,
          linewidth = 0.6,
          alpha = 0.85,
          show.legend = FALSE
        )
    }

    p13 <- p13 +
      ggplot2::geom_point(
        size = 3,
        alpha = 0.95
      ) +
      ggplot2::labs(
        title = paste0(
          "Candidate PCA — ",
          contrast_name
        ),
        subtitle = paste0(
          nrow(
            candidate_log2_rpm
          ),
          " miRNAs selected at ",
          candidate_label,
          "; exploratory post-selection visualization"
        ),
        x = sprintf(
          "PC1 (%.1f%%)",
          100 * variance[1]
        ),
        y = sprintf(
          "PC3 (%.1f%%)",
          100 * variance[3]
        ),
        color = NULL
      ) +
      ggplot2::theme_classic(
        base_size = 10
      ) +
      ggplot2::theme(
        plot.title = ggplot2::element_text(
          face = "bold"
        ),
        legend.position = "right"
      )

    save_ggplot_pdf(
      plot = p13,
      filename = file.path(
        output_dir,
        paste0(
          pca_prefix,
          "_pc13.pdf"
        )
      ),
      width = 7,
      height = 5
    )
  }

  invisible(
    list(
      pca = pca,
      coordinates = pca_df,
      variance = candidate_variance,
      miRNAs = rownames(
        candidate_log2_rpm
      ),
      candidate_type = candidate_type,
      plot_PC1_PC2 = p
    )
  )
}


