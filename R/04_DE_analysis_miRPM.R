      c(
        -2,
        0,
        2
      ),
      c(
        "navy",
        "white",
        "firebrick3"
      )
    ),
    top_annotation = annotation,
    column_split = heatmap_metadata[[group_variable]],
    cluster_rows = length(selected_miRNAs) > 1L,
    cluster_columns = FALSE,
    show_column_names = FALSE,
    show_row_names = TRUE,
    row_names_gp = grid::gpar(
      fontsize = 8
    ),
    column_title = paste0(
      contrast_name,
      " — ",
      candidate_label
