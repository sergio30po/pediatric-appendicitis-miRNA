add_audit_significance <- function(
    results_table
) {

  results_table$Holm <- stats::p.adjust(
    results_table$p_value,
    method = "holm"
  )

  results_table$raw_significant <- (
    !is.na(
      results_table$p_value
    ) &
      results_table$p_value < alpha_raw
  )

  results_table$fdr_significant <- (
    !is.na(
      results_table$FDR
    ) &
      results_table$FDR < alpha_fdr
  )

  results_table$holm_significant <- (
    !is.na(
      results_table$Holm
    ) &
      results_table$Holm < alpha_fdr
  )

  results_table$significance_class <- dplyr::case_when(
    results_table$fdr_significant ~ "FDR < 0.05",
    results_table$raw_significant ~ "Raw p < 0.05 only",
    TRUE ~ "Not significant"
  )

  results_table
}


save_result_sets <- function(
    results_table,
    contrast_name
) {

  all_results <- results_table |>
    dplyr::arrange(
      FDR,
      p_value
    )

  raw_candidates <- all_results |>
    dplyr::filter(
      raw_significant
    )

  fdr_candidates <- all_results |>
    dplyr::filter(
      fdr_significant
    )

  holm_candidates <- all_results |>
    dplyr::filter(
      holm_significant
    )

  short_name <- paste0(
    contrast_code(contrast_name),
    ".csv"
  )

  utils::write.csv(
    all_results,
    file.path(
      tables_dir,
      short_name
    ),
    row.names = FALSE
  )

  utils::write.csv(
    raw_candidates,
    file.path(
      candidate_raw_dir,
      short_name
    ),
    row.names = FALSE
  )

  utils::write.csv(
    fdr_candidates,
    file.path(
      candidate_fdr_dir,
      short_name
    ),
    row.names = FALSE
  )

  utils::write.csv(
    holm_candidates,
    file.path(
      candidate_holm_dir,
      short_name
    ),
    row.names = FALSE
  )

  list(
    all = all_results,
    raw = raw_candidates,
    fdr = fdr_candidates,
    holm = holm_candidates
  )
}


run_mirpm_two_group <- function(
    rpm_matrix,
    metadata_subset,
    condition,
    group_order,
    contrast_name,
    positive_effect_label
) {

  result <- miRPM::perform_statistical_tests(
    miRNA_ftd = rpm_matrix,
    metadata = metadata_subset,
    condition = condition,
    output_file = NULL,
    assign_results = FALSE,
    alpha = alpha_fdr,
    p_adjust_method = "BH",
    detection_threshold = 0,
    pseudocount = 1,
    group_order = group_order,
    write_excel = FALSE
  )

  if (!identical(
    result$analysis_type,
    "two_group"
  )) {
    stop(
      contrast_name,
      " did not return a two-group miRPM analysis."
    )
  }

  results_table <- as.data.frame(
    result$results
  )

  results_table <- add_audit_significance(
    results_table
  )

  results_table$effect_direction_definition <- positive_effect_label

  results_table$direction <- dplyr::case_when(
    results_table$log2_median_ratio_group_1_vs_group_2 > 0 ~
      paste0(
        "Higher_in_",
        group_order[1]
      ),
    results_table$log2_median_ratio_group_1_vs_group_2 < 0 ~
      paste0(
        "Higher_in_",
        group_order[2]
      ),
    TRUE ~ "No_change"
  )

  saveRDS(
    result,
    file.path(
      native_dir,
      paste0(
        contrast_code(contrast_name),
        ".rds"
      )
    )
  )

  saved_sets <- save_result_sets(
    results_table,
    contrast_name
  )

  list(
    native = result,
    all_results = saved_sets$all,
    raw_candidates = saved_sets$raw,
    fdr_candidates = saved_sets$fdr,
    holm_candidates = saved_sets$holm
  )
}


plot_fdr_effect_summary <- function(
    analysis_result,
    contrast_name,
    title,
    x_label
) {

  plotting_table <- analysis_result$fdr_candidates

  if (nrow(plotting_table) == 0) {
    message(
      "No FDR < 0.05 candidates for effect plot: ",
      contrast_name
    )

    return(
      invisible(
        NULL
      )
    )
  }

  plotting_table <- plotting_table |>
    dplyr::arrange(
      log2_median_ratio_group_1_vs_group_2
    )

  plotting_table$miRNA <- factor(
    plotting_table$miRNA,
    levels = plotting_table$miRNA
  )

  plot_object <- ggplot2::ggplot(
    plotting_table,
    ggplot2::aes(
      x = log2_median_ratio_group_1_vs_group_2,
      y = miRNA
    )
  ) +
    ggplot2::geom_vline(
      xintercept = 0,
      linetype = "dashed",
      linewidth = 0.5
    ) +
    ggplot2::geom_segment(
      ggplot2::aes(
        x = 0,
        xend = log2_median_ratio_group_1_vs_group_2,
        yend = miRNA
      ),
      linewidth = 0.6
    ) +
    ggplot2::geom_point(
      size = 2.8
    ) +
    ggplot2::labs(
      title = title,
      subtitle = "RPM-based Mann-Whitney-Wilcoxon; BH-FDR < 0.05",
      x = x_label,
      y = NULL
    ) +
    ggplot2::theme_classic(
      base_size = 11
    ) +
    ggplot2::theme(
      plot.title = ggplot2::element_text(
        face = "bold"
      )
    )

