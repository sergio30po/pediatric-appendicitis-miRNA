# ==============================================================================
# 03_DANA_analysis.R
# ==============================================================================
#
# Project:
#   Pediatric appendicitis plasma miRNA-seq
#
# Script:
#   03_DANA_analysis.R
#
# Purpose:
#   Evaluate normalization performance using the original DANA framework
#   (Data-driven Assessment of Normalization Methods for miRNA-seq).
#
# Role in pipeline:
#   Normalization assessment / methodological validation.
#
#   This script:
#     - uses the complete raw miRNA count matrix from the selected cohort;
#     - inherits the canonical clinical labels created by script 01;
#     - validates cohort/metadata consistency inherited from script 01;
#     - verifies mathematical equivalence between project RPM and Total Count;
#     - maps miRNAs to DANA miRBase v22 genomic coordinates;
#     - defines polycistronic miRNA clusters;
#     - defines DANA positive and negative controls;
#     - applies the normalization methods implemented by DANA;
#     - adds project RPM as the Total-Count-equivalent normalization;
#     - evaluates normalization using the original DANA cc and mscr metrics;
#     - records complete control, coordinate and normalization traceability.
#
# IMPORTANT:
#   DANA is applied to the COMPLETE raw miRNA count matrix generated by script
#   01, before the 100-RPM / 50%-prevalence feature filter.
#
#   This is required because DANA uses poorly expressed miRNAs as negative
#   controls. Applying the downstream expression filter first would invalidate
#   that component of the method.
#
# Canonical clinical groups inherited from script 01:
#   NIA    = non-inflamed appendix
#   Mild   = mild appendicitis
#   Severe = severe appendicitis
#
#   NIA is NOT a healthy-control cohort.
#
# DANA control thresholds:
#   tZero = 2
#   tPoor = 5
#   tWell = 100
#
# Polycistronic cluster threshold:
#   <= 10,000 bp
#
# Normalization methods assessed:
#   UQ
#   Median (returned by DANA as Med)
#   TMM
#   DESeq
#   PoissonSeq
#   QN
#   RUVg
#   RUVs
#   RUVr
#   RPM
#
# Total Count (TC):
#   TC is not evaluated as a duplicated method because project RPM uses:
#
#       raw count / complete raw-count library size * 1,000,000
#
#   which is mathematically equivalent to DANA Total Count normalization.
#   Numerical equivalence is explicitly verified before DANA assessment.
#
# DANA interpretation:
#   cc:
#     preservation of biological correlation structure among clustered positive
#     controls. Higher values, ideally close to 1, indicate better preservation.
#
#   mscr:
#     relative reduction of unwanted correlation among negative controls.
#     Higher values indicate stronger removal of handling effects.
#
#   No post hoc composite score is calculated or used to rank methods.
#
# IMPORTANT FOR DOWNSTREAM ANALYSIS:
#   The normalized matrices generated here are DANA assessment products only.
#   They are not automatically substituted into the differential-expression
#   workflow. edgeR and DESeq2 downstream analyses continue to use raw counts
#   with their method-appropriate normalization/modeling procedures.
#
# Inputs:
#   results/<analysis_id>/counts_analysis_samples.rds
#   results/<analysis_id>/RPM_counts_all_miRNAs.rds
#   results/<analysis_id>/metadata_analysis_samples.rds
#
# Main outputs:
#   results/<analysis_id>/DANA/
#
#     DANA_group_summary.csv
#     DANA_RPM_TC_equivalence.csv
#     miRNA_name_mapping.csv
#     DANA_coordinate_coverage_summary.csv
#     DANA_miRNAs_without_coordinates.csv
#     DANA_unclustered_miRNAs.csv
#     DANA_miRNA_clusters.csv
#     DANA_cluster_sizes.csv
#     DANA_cluster_summary.csv
#     DANA_control_thresholds.csv
#     DANA_controls.csv
#     DANA_control_summary.csv
#     DANA_positive_control_clusters.csv
#     DANA_normalization_method_summary.csv
#     DANA_control_availability_by_method.csv
#     DANA_assessment_results.csv
#     DANA_assessment_results.rds
#     normalized_matrices/
#     03_final_QC_summary.csv
#     sessionInfo.txt
#
# Figures:
#   figures/<analysis_id>/DANA/
#
#     DANA_count_distribution.png
#     DANA_mean_SD.png
#     DANA_normalization_assessment.pdf
#     DANA_normalization_assessment.tiff
#     DANA_normalization_assessment.png
#
# Methodological decisions:
#   - No samples are removed in this script.
#   - No artificial positive or negative controls are added.
#   - The original DANA cc and mscr metrics are preserved.
#   - Clinical grouping is inherited from metadata$Phenotype generated in 01;
#     this script never remaps Apend_type values to new display labels.
#   - DANA's bundled human miRBase v22 coordinates are supplied explicitly to
#     defineClusters() to avoid a namespace-dependent issue in DANA 1.4.0.
#
# Reproducibility:
#   Cohort membership and clinical labels are inherited from scripts 00/01.
#   All DANA thresholds, control sets, normalization methods and assessment
#   outputs are exported explicitly.
#
# ==============================================================================


