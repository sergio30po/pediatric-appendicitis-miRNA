message(
  "Applying DANA normalization methods..."
)


normalized <- tryCatch(
  {
    DANA::applyNormalization(
      data = counts_dana,
      groups = groups,
      method = normalization_methods_requested
    )
  },
  error = function(e) {
    stop(
      "DANA normalization failed: ",
      conditionMessage(e),
      call. = FALSE
    )
  }
)


if (
  !is.list(normalized) ||
  length(normalized) == 0L ||
  is.null(names(normalized))
) {
  stop(
    "DANA::applyNormalization() did not return a valid named list of matrices.",
    call. = FALSE
  )
}


# Project RPM is added explicitly as the Total-Count-equivalent method.
normalized$RPM <- RPM_dana


missing_expected_methods <- setdiff(
  expected_normalized_methods,
  names(normalized)
)


if (length(missing_expected_methods) > 0L) {
  stop(
    "DANA did not return all expected normalization methods: ",
    paste(
      missing_expected_methods,
      collapse = ", "
    ),
    call. = FALSE
  )
}


unexpected_methods <- setdiff(
  names(normalized),
  expected_normalized_methods
)


if (length(unexpected_methods) > 0L) {
  warning(
    "DANA returned additional normalization method(s): ",
    paste(
      unexpected_methods,
      collapse = ", "
    ),
    call. = FALSE
  )
}


expected_samples <- colnames(counts_dana)
expected_miRNAs <- rownames(counts_dana)


normalization_method_rows <- list()


for (
  method_name in names(normalized)
) {
  normalized_matrix <- as.matrix(
    normalized[[method_name]]
  )

  storage.mode(normalized_matrix) <- "numeric"

  if (
    is.null(rownames(normalized_matrix)) ||
    is.null(colnames(normalized_matrix))
  ) {
    stop(
      "Normalization method ",
      method_name,
      " returned a matrix without row/column names.",
      call. = FALSE
    )
  }

  if (!setequal(
    colnames(normalized_matrix),
    expected_samples
  )) {
    stop(
      "Normalization method ",
      method_name,
      " returned a different set of samples.",
      call. = FALSE
    )
  }

  unknown_miRNAs <- setdiff(
    rownames(normalized_matrix),
    expected_miRNAs
  )

  if (length(unknown_miRNAs) > 0L) {
    stop(
      "Normalization method ",
      method_name,
      " returned miRNAs absent from the raw matrix: ",
      paste(
        head(
          unknown_miRNAs,
          10L
        ),
        collapse = ", "
      ),
      call. = FALSE
    )
  }

  normalized_matrix <- normalized_matrix[
    ,
    expected_samples,
    drop = FALSE
  ]

  if (
    anyNA(normalized_matrix) ||
    any(!is.finite(normalized_matrix))
  ) {
    stop(
      "Normalization method ",
      method_name,
      " produced missing or non-finite values.",
      call. = FALSE
    )
  }

  if (any(normalized_matrix < 0)) {
    stop(
      "Normalization method ",
      method_name,
      " produced negative values.",
      call. = FALSE
    )
  }

  normalized[[method_name]] <- normalized_matrix

  normalization_method_rows[[method_name]] <- data.frame(
    method = method_name,
    n_miRNAs = nrow(normalized_matrix),
    n_samples = ncol(normalized_matrix),
    full_feature_set_retained = setequal(
      rownames(normalized_matrix),
      expected_miRNAs
    ),
    all_values_finite = TRUE,
    assessment_only = TRUE,
    stringsAsFactors = FALSE
  )

  message(
    method_name,
    ": ",
    nrow(normalized_matrix),
    " miRNAs retained."
  )
}


normalization_method_summary <- do.call(
  rbind,
  normalization_method_rows
)

rownames(normalization_method_summary) <- NULL


utils::write.csv(
  normalization_method_summary,
  prepare_output_file(
    file.path(
      dana_results_dir,
      "DANA_normalization_method_summary.csv"
    )
  ),
  row.names = FALSE
)


