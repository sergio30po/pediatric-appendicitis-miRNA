# ==============================================================================

for (
  object_name in c(
    "counts",
    "RPM_counts"
  )
) {
  expression_matrix <- get(object_name)

  if (
    nrow(expression_matrix) == 0L ||
    ncol(expression_matrix) == 0L
  ) {
    stop(
      object_name,
      " is empty.",
      call. = FALSE
    )
  }

  if (
    is.null(rownames(expression_matrix)) ||
    is.null(colnames(expression_matrix))
  ) {
    stop(
      object_name,
      " must contain miRNA row names and sample column names.",
      call. = FALSE
    )
  }

  if (
    anyDuplicated(rownames(expression_matrix)) > 0L ||
    anyDuplicated(colnames(expression_matrix)) > 0L
  ) {
    stop(
      object_name,
      " contains duplicated miRNA or sample identifiers.",
      call. = FALSE
    )
  }

  if (
    anyNA(expression_matrix) ||
    any(!is.finite(expression_matrix)) ||
    any(expression_matrix < 0)
  ) {
    stop(
      object_name,
      " contains missing, non-finite or negative values.",
      call. = FALSE
    )
  }
}


