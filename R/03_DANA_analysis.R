# ==============================================================================
# 5.3 Define polycistronic clusters
# ==============================================================================

message(
  "Defining DANA polycistronic miRNA clusters..."
)


chr_dana <- mirbase_coordinates[
  genes_with_coordinates,
  "chromosome"
]

pos_dana <- mirbase_coordinates[
  genes_with_coordinates,
  "position"
]


clusters <- DANA::defineClusters(
  genes = genes_with_coordinates,
  chr = chr_dana,
  pos = pos_dana,
  threshold = DANA_CLUSTER_DISTANCE_BP
)


if (
  is.null(clusters) ||
  length(clusters) == 0L ||
  is.null(names(clusters))
) {
  stop(
    "DANA did not return a valid named cluster vector.",
    call. = FALSE
  )
}


if (!all(
  names(clusters) %in% genes_with_coordinates
