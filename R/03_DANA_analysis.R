# ==============================================================================
# 4.7 Verify RPM / Total Count equivalence
# ==============================================================================

library_sizes <- colSums(counts)


if (
  anyNA(library_sizes) ||
  any(!is.finite(library_sizes)) ||
  any(library_sizes <= 0)
) {
  stop(
    "At least one sample has an invalid raw-count library size.",
    call. = FALSE
  )
}


TC_reference <- sweep(
  counts,
  2L,
  library_sizes,
  FUN = "/"
) * 1e6


TC_reference <- TC_reference[
  rownames(RPM_counts),
  colnames(RPM_counts),
  drop = FALSE
]


absolute_difference <- abs(
  TC_reference - RPM_counts
)


maximum_absolute_difference <- max(
  absolute_difference,
  na.rm = TRUE
)

mean_absolute_difference <- mean(
  absolute_difference,
  na.rm = TRUE
)


rpm_tc_equivalent <- isTRUE(
  all.equal(
    TC_reference,
    RPM_counts,
    tolerance = 1e-10,
    check.attributes = FALSE
  )
)


rpm_tc_equivalence <- data.frame(
  comparison = "RPM_vs_Total_Count",
  equivalent = rpm_tc_equivalent,
  tolerance = 1e-10,
  maximum_absolute_difference = maximum_absolute_difference,
  mean_absolute_difference = mean_absolute_difference,
  denominator = "complete_raw_count_matrix_column_sum",
  stringsAsFactors = FALSE
)


utils::write.csv(
  rpm_tc_equivalence,
  prepare_output_file(
    file.path(
      dana_results_dir,
      "DANA_RPM_TC_equivalence.csv"
    )
  ),
  row.names = FALSE
)


if (!rpm_tc_equivalent) {
  stop(
    "RPM and Total Count normalization are not numerically equivalent. ",
    "Maximum absolute difference: ",
    signif(
      maximum_absolute_difference,
      6
    ),
    ". Check the RPM denominator and sample alignment before continuing.",
    call. = FALSE
  )
}


message(
