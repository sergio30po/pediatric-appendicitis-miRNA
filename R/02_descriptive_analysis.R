draw_heatmap_gtable <- function(
    heatmap_gtable,
    filename,
    type = c(
      "pdf",
      "tiff"
    )
) {
  
  type <- match.arg(
    type
  )
  
  
  draw_function <- function() {
    
    grid::grid.newpage()
    
    grid::grid.draw(
      heatmap_gtable
    )
  }
  
  
  if (
    type == "pdf"
  ) {
    
    draw_to_pdf(
      filename = filename,
      width = 7,
