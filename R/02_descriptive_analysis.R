# ==============================================================================
# 02_descriptive_analysis.R
# ==============================================================================
#
# Project:
#   Pediatric appendicitis plasma miRNA-seq
#
# Script:
#   02_descriptive_analysis.R
#
# Purpose:
#   Perform descriptive and exploratory quality-control analyses on the final
#   cohort and the complete set of miRNAs retained by the prespecified
#   abundance/prevalence filter.
#
# Role in pipeline:
#   Global expression QC and exploratory descriptive analysis.
#
#   This script:
#     - validates the filtered RPM objects generated by script 01;
#     - performs PCA using all filtered miRNAs;
#     - quantifies variance explained by principal components;
#     - generates global PCA plots;
#     - evaluates non-destructive sample-level QC/outlier metrics;
#     - evaluates an exploratory sequencing-based hemolysis proxy;
#     - formally tests the hemolysis proxy across the three clinical groups;
#     - evaluates associations between PCs and biological/technical covariates;
#     - generates a fully unsupervised global heatmap;
#     - records clustering order and exploratory sample clusters;
#     - generates global-expression QC figures suitable for supplementary use.
#
# Important manuscript distinction:
#   The PCA and heatmap generated here use ALL miRNAs retained after the
#   prespecified expression filter.
#
#   They are global-expression QC / supplementary analyses.
#
#   No downstream differential-expression result or candidate prioritization
#   is used to construct these analyses.
#
# Statistical principles:
#   - PCA:
#       log2(RPM + 1), feature-centered and feature-scaled.
#
#   - PCA is exploratory/descriptive.
#
#   - No sample is automatically removed because of PCA position,
#     dendrogram position or QC flags.
#
#   - Sample QC:
#       robust z-scores based on median absolute deviation (MAD).
#
#   - Hemolysis:
#       exploratory sequencing-based proxy:
#
#         log2(miR-451a RPM + 1) -
#         log2(miR-23a-3p RPM + 1)
#
#       qPCR-specific delta-Cq thresholds are not applied.
#
#   - Hemolysis phenotype comparison:
#       Kruskal-Wallis test across Apend_type groups.
#
#   - PC/covariate associations:
#       continuous variables -> Spearman correlation
#       categorical variables -> Kruskal-Wallis test
#
#       Benjamini-Hochberg FDR is calculated across the complete PC/covariate
#       association audit.
#
# Inputs:
#   results/<analysis_id>/filtered_RPM.rds
#   results/<analysis_id>/RPM_counts_all_miRNAs.rds
#   results/<analysis_id>/metadata_analysis_samples.rds
#   results/<analysis_id>/Metrics_analysis_samples.rds
#
# Main outputs:
#   PCA_sample_coordinates.csv
#   PCA_variance_explained.csv
#   PCA_variance_summary.csv
#
#   outlier_evaluation_summary.csv
#
#   hemolysis_proxy.csv
#   hemolysis_phenotype_test.csv
#
#   PC_covariate_associations.csv
#   batch_audit_status.csv
#
#   global_heatmap_feature_manifest.csv
#   global_heatmap_miRNA_cluster_order.csv
#   global_heatmap_sample_cluster_order.csv
#   global_heatmap_sample_clusters_k3.csv
#   global_heatmap_cluster_vs_phenotype.csv
#
#   descriptive_stats.csv
#   02_final_QC_summary.csv
#
# Figures:
#   figures/<analysis_id>/PCA/
#   figures/<analysis_id>/heatmaps/
#   figures/<analysis_id>/outlier_assessment/
#   figures/<analysis_id>/hemolysis/
#   figures/<analysis_id>/global_expression/
#
# Reproducibility:
#   All analyses operate on the exact cohort, feature set and canonical clinical
#   labels generated by script 01. This script never changes cohort membership,
#   feature inclusion or clinical-group definitions.
#
# ==============================================================================


