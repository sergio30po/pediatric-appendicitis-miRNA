robust_z <- function(x) {
  
  x <- as.numeric(
    x
  )
  
  
  med <- stats::median(
    x,
    na.rm = TRUE
  )
  
  
  mad_value <- stats::mad(
    x,
    center = med,
    constant = 1.4826,
    na.rm = TRUE
  )
  
  
  if (
    !is.finite(
      mad_value
    ) ||
    mad_value == 0
  ) {
    
    return(
      rep(
        0,
        length(
          x
        )
      )
    )
  }
  
  
  (
    x -
      med
  ) / mad_value
}


