      draw = draw_function
    )
    
  } else {
    
    draw_to_tiff(
      filename = filename,
      width = 7,
      height = 5.2,
      units = "in",
      res = 600,
      compression = "lzw",
      draw = draw_function
    )
  }
  
  
  invisible(
    filename
  )
}


