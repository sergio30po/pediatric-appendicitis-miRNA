get_ellipse_data <- function(
    data,
    group_var,
    x_var,
    y_var,
    minimum_group_n = 3L
) {
  
  required_columns <- c(
    group_var,
    x_var,
    y_var
  )
  
  
  if (!all(
    required_columns %in%
    colnames(data)
  )) {
    
    return(
      data[
        0,
        ,
        drop = FALSE
      ]
    )
  }
  
  
  keep_complete <- stats::complete.cases(
    data[
      ,
      required_columns,
      drop = FALSE
    ]
  )
  
  
  ellipse_data <- data[
    keep_complete,
    ,
    drop = FALSE
  ]
  
  
  if (nrow(
    ellipse_data
  ) == 0L) {
    
    return(
      ellipse_data
    )
  }
  
  
  group_values <- as.character(
    ellipse_data[[group_var]]
  )
  
  
  group_counts <- table(
    group_values
  )
  
  
  eligible_groups <- names(
    group_counts[
      group_counts >= minimum_group_n
    ]
  )
  
  
  ellipse_data[
    group_values %in%
      eligible_groups,
    ,
    drop = FALSE
  ]
}


