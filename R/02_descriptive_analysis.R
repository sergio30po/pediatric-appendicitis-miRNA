pc_number_for_threshold <- function(
    cumulative_pct,
    threshold
) {
  
  hit <- which(
    cumulative_pct >= threshold
  )
  
  
  if (length(
    hit
  ) == 0L) {
    
    return(
      NA_integer_
    )
  }
  
  
  hit[1L]
}


