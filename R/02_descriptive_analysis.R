draw_global_expression_figure <- function(
    filename,
    type = c(
      "pdf",
      "tiff"
    )
) {
  
  type <- match.arg(
    type
  )
  
  
  draw_function <- function() {
    
    grid::grid.newpage()
    
    
    layout <- grid::grid.layout(
      
      nrow = 2L,
      
      ncol = 1L,
      
      heights = grid::unit(
        c(
          0.43,
          0.57
        ),
        "null"
      )
    )
    
    
    root_viewport <- grid::viewport(
      layout = layout
    )
    
    
    grid::pushViewport(
      root_viewport
    )
    
    
    print(
      p_pca_global,
      vp = grid::viewport(
        layout.pos.row = 1L,
        layout.pos.col = 1L
      ),
      newpage = FALSE
    )
    
    
    grid::pushViewport(
      grid::viewport(
        layout.pos.row = 2L,
        layout.pos.col = 1L
      )
    )
    
    
    grid::grid.draw(
      heatmap_object$gtable
    )
    
    
    grid::popViewport()
    
    grid::popViewport()
  }
  
  
  if (
    type == "pdf"
  ) {
    
    draw_to_pdf(
      filename = filename,
      width = 7,
      height = 9,
      draw = draw_function
    )
    
  } else {
    
    draw_to_tiff(
      filename = filename,
      width = 7,
      height = 9,
      units = "in",
      res = 600,
      compression = "lzw",
      draw = draw_function
    )
  }
  
  
  invisible(
    filename
  )
}


